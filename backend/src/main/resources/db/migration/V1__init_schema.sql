-- GroomDesk V1: core schema (CLAUDE.md §3)
-- Money: NUMERIC(12,2). Percentages: NUMERIC(5,2). Time: timestamptz (UTC).
-- Enums are VARCHAR + CHECK (maps cleanly to JPA @Enumerated(STRING)).

CREATE TABLE franchise (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(120)  NOT NULL,
    owner_name       VARCHAR(120)  NOT NULL,
    owner_phone      VARCHAR(10)   NOT NULL,
    gstin            VARCHAR(15),
    royalty_percent  NUMERIC(5,2)  NOT NULL CHECK (royalty_percent BETWEEN 0 AND 100),
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE TABLE outlet (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    franchise_id  BIGINT        NOT NULL REFERENCES franchise (id),
    code          VARCHAR(10)   NOT NULL UNIQUE,
    name          VARCHAR(120)  NOT NULL,
    area          VARCHAR(120),
    city          VARCHAR(80)   NOT NULL,
    tax_rate      NUMERIC(5,2)  NOT NULL CHECK (tax_rate BETWEEN 0 AND 100),
    active        BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(60)   NOT NULL UNIQUE,
    password_hash  VARCHAR(100)  NOT NULL,
    full_name      VARCHAR(120)  NOT NULL,
    role           VARCHAR(20)   NOT NULL
                   CHECK (role IN ('HQ_ADMIN', 'FRANCHISE_OWNER', 'OUTLET_MANAGER', 'CASHIER')),
    franchise_id   BIGINT        REFERENCES franchise (id),
    outlet_id      BIGINT        REFERENCES outlet (id)
);

CREATE TABLE barber (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id           BIGINT        NOT NULL REFERENCES outlet (id),
    name                VARCHAR(120)  NOT NULL,
    phone               VARCHAR(10),
    commission_percent  NUMERIC(5,2)  NOT NULL CHECK (commission_percent BETWEEN 0 AND 100),
    active              BOOLEAN       NOT NULL DEFAULT TRUE
);

-- Central service menu set by HQ. code = billing shortcut key ("1".."9"), optional.
CREATE TABLE service (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(4)     UNIQUE,
    name          VARCHAR(120)   NOT NULL,
    category      VARCHAR(10)    NOT NULL
                  CHECK (category IN ('HAIR', 'BEARD', 'FACIAL', 'COMBO', 'OTHER')),
    price         NUMERIC(12,2)  NOT NULL CHECK (price >= 0),
    duration_min  INTEGER        NOT NULL CHECK (duration_min > 0),
    active        BOOLEAN        NOT NULL DEFAULT TRUE
);

-- Shared across ALL outlets.
CREATE TABLE customer (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone                  VARCHAR(10)   NOT NULL CHECK (phone ~ '^[6-9][0-9]{9}$'),
    name                   VARCHAR(120)  NOT NULL,
    notes                  TEXT,
    preferred_barber_id    BIGINT        REFERENCES barber (id),
    first_visit_outlet_id  BIGINT        NOT NULL REFERENCES outlet (id),
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now()
);
-- Unique index doubles as the customer(phone) lookup index.
CREATE UNIQUE INDEX ux_customer_phone ON customer (phone);

CREATE TABLE bill (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_no         VARCHAR(32)    NOT NULL UNIQUE,
    outlet_id       BIGINT         NOT NULL REFERENCES outlet (id),
    customer_id     BIGINT         NOT NULL REFERENCES customer (id),
    cashier_id      BIGINT         NOT NULL REFERENCES app_user (id),
    subtotal        NUMERIC(12,2)  NOT NULL,
    discount        NUMERIC(12,2)  NOT NULL DEFAULT 0,
    taxable_amount  NUMERIC(12,2)  NOT NULL,
    tax_rate        NUMERIC(5,2)   NOT NULL,
    tax_amount      NUMERIC(12,2)  NOT NULL,
    total           NUMERIC(12,2)  NOT NULL,
    payment_mode    VARCHAR(10)    NOT NULL CHECK (payment_mode IN ('CASH', 'UPI', 'CARD')),
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CHECK (discount >= 0 AND discount <= subtotal)
);
CREATE INDEX idx_bill_outlet_created_at ON bill (outlet_id, created_at);
CREATE INDEX idx_bill_customer ON bill (customer_id);

CREATE TABLE bill_item (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id            BIGINT         NOT NULL REFERENCES bill (id) ON DELETE CASCADE,
    service_id         BIGINT         NOT NULL REFERENCES service (id),
    barber_id          BIGINT         NOT NULL REFERENCES barber (id),
    price              NUMERIC(12,2)  NOT NULL,
    commission_amount  NUMERIC(12,2)  NOT NULL
);
CREATE INDEX idx_bill_item_barber ON bill_item (barber_id);
-- Not in §3's list, but every receipt/report loads items by bill.
CREATE INDEX idx_bill_item_bill ON bill_item (bill_id);
