-- Split payments: one bill paid partly by cash and partly by UPI or card (franchise owner request).
-- A single-mode bill keeps its mode in bill.payment_mode and has no bill_payment rows.
-- A split bill has payment_mode = 'MIXED' and one bill_payment row per mode; the rows add up to bill.total.

-- Allow MIXED. The V1 check was declared inline, so look its name up instead of assuming it.
DO $$
DECLARE
    c record;
BEGIN
    FOR c IN
        SELECT con.conname
        FROM pg_constraint con
        WHERE con.conrelid = 'bill'::regclass
          AND con.contype = 'c'
          AND pg_get_constraintdef(con.oid) LIKE '%payment_mode%'
    LOOP
        EXECUTE format('ALTER TABLE bill DROP CONSTRAINT %I', c.conname);
    END LOOP;
END $$;

ALTER TABLE bill
    ADD CONSTRAINT bill_payment_mode_check CHECK (payment_mode IN ('CASH', 'UPI', 'CARD', 'MIXED'));

CREATE TABLE bill_payment (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id  BIGINT         NOT NULL REFERENCES bill (id) ON DELETE CASCADE,
    mode     VARCHAR(10)    NOT NULL CHECK (mode IN ('CASH', 'UPI', 'CARD')),
    amount   NUMERIC(12,2)  NOT NULL CHECK (amount > 0),
    UNIQUE (bill_id, mode)
);
